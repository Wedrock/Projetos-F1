const cache = new Map<string, string>();

/** A race control message in Portuguese (unknown phrases stay in English). */
export function raceControlPt(message: string | null | undefined): string {
  if (!message) return "";
  const hit = cache.get(message);
  if (hit !== undefined) return hit;
  let text = message.toUpperCase();
  for (const [pattern, replacement] of RULES) {
    text = typeof replacement === "string"
      ? text.replace(pattern, replacement)
      : text.replace(pattern, (...args) => replacement(...(args as string[])));
  }
  text = text.split(SC).join("SAFETY CAR").replace(/  +/g, " ");
  if (cache.size > 2000) cache.clear();
  cache.set(message, text);
  return text;
}
